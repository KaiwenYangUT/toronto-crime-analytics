#!/usr/bin/env bash
# Regenerate parity/r/PATCHES.md from the real diffs between _reference/ and build/r-work/.
set -euo pipefail
root="$(pwd -P)"
out="$root/parity/r/PATCHES.md"
d() { (cd "$root" && diff -u --label "a/$1" --label "b/$2" "$3" "$4" || true); }
{
cat <<'HEAD'
# PATCHES: how the R originals were run

Generated by `parity/r/make_patches_md.sh` from the actual files; do not edit by hand.
The originals in `_reference/` are read-only and never modified. Every re-run happens on a copy under `build/r-work/`.

**Rule:** a patch may change where data is read from, remove a network call, or add export hooks.
It never changes modelling logic. Hook chunks only read objects and write files, and none of them draws random numbers
(JSC370 bagging, random forest and GBM take their RNG state from earlier draws, so the stream must stay untouched).

## Explorer (`_reference/explorer` → `build/r-work/explorer`)
No source patch.
- `scripts/build_data.R` takes the raw-data directory as an argument, so it reads `data/raw/` as-is.
- `tests/test_shiny.R` and `scripts/*.R` fall back to the normal R library path when `../../work/r-library` is absent, which it is from `build/r-work/explorer`. The project-local `.r-lib` is used through `R_LIBS_USER`.
- Runner: `parity/r/run_explorer.sh`. Fixtures: `parity/r/explorer_fixtures.R`.

## STA303 (`_reference/STA303_Final_Report.Rmd` → `build/r-work/sta303`)
No path patch: the data directory is read from `CRIME_DATA_DIR`, set to `data/raw`.
Eleven export-hook chunks are inserted after the closing fence of the chunk named by each anchor. No original line changes.
The last fence of the original has no trailing newline; the copy adds one (whitespace only).
Helpers: `parity/r/hooks/sta303_hooks.R`. Builder: `parity/r/make_sta303_copy.R`. Runner: `parity/r/run_sta303.sh`.

```diff
HEAD
d STA303_Final_Report.Rmd STA303_Final_Report.Rmd "$root/_reference/STA303_Final_Report.Rmd" "$root/build/r-work/sta303/STA303_Final_Report.Rmd"
cat <<'MID'
```

## JSC370 (`_reference/robbery/Final_Project.Rmd` → `build/r-work/jsc370`)
Two data patches (patch 1: seven GitHub URLs become `../../../data/raw/…`; patch 2: the workbook is read from `data/raw` and `download.file()` is commented out because it would overwrite the xlsx) plus three export hooks.
Helpers: `parity/r/hooks/jsc370_hooks.R`. Builder: `parity/r/make_jsc370_copy.R`. Runner: `parity/r/run_jsc370.sh`.

```diff
MID
d robbery/Final_Project.Rmd Final_Project.Rmd "$root/_reference/robbery/Final_Project.Rmd" "$root/build/r-work/jsc370/Final_Project.Rmd"
echo '```'
cat <<'TAIL'

## Chart widgets (`_reference/robbery/scripts/build_visual_widgets.R`, `variable.Rmd` → `build/r-work/charts`)
No patch. Both run unmodified on a work copy whose `data/` is a symlink to the pinned raw snapshot (`parity/r/run_charts.sh`). The plotted arrays are read from the widget JSON by `parity/r/extract_chart_data.py`; nothing in the originals is changed or hooked.
TAIL
} > "$out"
echo "wrote $out ($(wc -l < "$out") lines)"
