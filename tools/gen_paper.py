"""Generate what the paper reads from results/: numbers.tex, the two tables and the four figure PDFs.

Every number in the paper reaches it through \\res{results.key:path} (numbers.tex) or through a generated
table, both formatted by the same display formats as the site (results/index.json plus
design/display_formats.json; the formatting mirrors web/src/lib/results.ts). A missing value or format
is an error. Run from the repo root with the project environment: python tools/gen_paper.py [all|numbers|tables|figures]
"""

from __future__ import annotations

import json
import re
import subprocess
import sys
from decimal import ROUND_HALF_UP, Decimal
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
PAPER = ROOT / "paper"
GENERATED = PAPER / "generated"
BUILD = PAPER / "build"
SECTIONS = PAPER / "sections"
HEADER = "% Generated by tools/gen_paper.py from results/. Do not edit by hand.\n"
DESIGN_A = "A_neighbourhood_grouped_5fold_cv"
DESIGN_B = "B_temporal_holdout_train_to_2021_test_2022_2023"


def load_results() -> dict[str, object]:
    return {
        key: json.loads((ROOT / entry["file"]).read_text())["values"]
        for key, entry in json.loads((ROOT / "results" / "index.json").read_text()).items()
    }


def load_formats() -> dict[str, dict]:
    index = json.loads((ROOT / "results" / "index.json").read_text())
    formats = {f"{k}:{p}": f for k, e in index.items() for p, f in e["formats"].items()}
    for pattern, fmt in json.loads((ROOT / "design" / "display_formats.json").read_text()).items():
        if not pattern.startswith("_"):
            formats[pattern] = fmt
    return formats


RESULTS = load_results()
FORMATS = load_formats()


def split_ref(ref: str) -> tuple[str, list[str]]:
    key, sep, path = ref.partition(":")
    if not sep:
        raise ValueError(f"Result reference {ref!r} must look like results.key:path")
    return key, path.split(".")


def get_value(ref: str) -> object:
    key, path = split_ref(ref)
    if key not in RESULTS:
        raise KeyError(f"Unknown results key in {ref!r}")
    node = RESULTS[key]
    for part in path:
        if isinstance(node, list):
            node = node[int(part)]
        elif isinstance(node, dict) and part in node:
            node = node[part]
        else:
            raise KeyError(f"No value at {ref}")
    return node


def format_for(ref: str) -> dict:
    key, path = split_ref(ref)
    best, best_wild = None, 1 << 30
    for pattern, fmt in FORMATS.items():
        pat_key, sep, pat_path = pattern.partition(":")
        if sep and pat_key != key:
            continue
        segs = (pat_path if sep else pattern).split(".")
        if len(segs) != len(path) or any(
            s != "*" and s != p for s, p in zip(segs, path, strict=True)
        ):
            continue
        wild = segs.count("*")
        if wild < best_wild:
            best, best_wild = fmt, wild
    if best is None:
        raise KeyError(f"No display format for {ref}")
    return best


def format_number(v: float, fmt: dict) -> str:
    """Same text as formatNumber in web/src/lib/results.ts (Intl en-CA; ICU rounds the shortest decimal half up)."""
    if fmt.get("p"):
        # JS toFixed rounds an exact tie up (Python's format rounds it to even)
        return (
            "< 0.001"
            if v < 0.001
            else str(Decimal(v).quantize(Decimal("0.001"), rounding=ROUND_HALF_UP))
        )
    decimals = fmt.get("decimals", 0)
    scaled = v * 100 if fmt.get("percent") else v
    exact = Decimal(repr(float(scaled))).quantize(
        Decimal(1).scaleb(-decimals), rounding=ROUND_HALF_UP
    )
    text = format(exact, "f" if fmt.get("plain") else ",f")
    return f"{text}%" if fmt.get("percent") else text


def fmt(ref: str) -> str:
    value = get_value(ref)
    if isinstance(value, bool) or not isinstance(value, int | float):
        raise TypeError(f"{ref} is not a number")
    return format_number(float(value), format_for(ref))


def tex(text: str) -> str:
    """Escape a formatted number for LaTeX text (true minus sign, escaped percent)."""
    return text.replace("%", r"\%").replace("-", "\u2212").replace("< ", r"\ensuremath{<}\,")


# Shorthand macros in paper.tex: \resG{path} is \res{explain.sta303_v2:path}, and so on.
PREFIX = {
    "": "",
    "G": "explain.sta303_v2:",
    "A": f"predict.ablation:designs.{DESIGN_A}.",
    "B": f"predict.ablation:designs.{DESIGN_B}.",
    "I": "predict.inference_vs_prediction:",
}


def used_refs() -> list[str]:
    refs: set[str] = set()
    for path in sorted(SECTIONS.glob("*.tex")):
        for variant, key in re.findall(r"\\res([GABI]?)\{([^}]+)\}", path.read_text()):
            refs.add(PREFIX[variant] + key)
    return sorted(refs)


def write_numbers() -> None:
    lines = [HEADER]
    refs = used_refs()
    for ref in refs:
        lines.append(f"\\expandafter\\gdef\\csname tcares:{ref}\\endcsname{{{tex(fmt(ref))}}}\n")
    GENERATED.mkdir(parents=True, exist_ok=True)
    (GENERATED / "numbers.tex").write_text("".join(lines))
    print(f"numbers.tex: {len(refs)} values")


RUNG_LABEL = {
    "L1": "Time only",
    "L2": "+ place",
    "L3": "+ census",
    "L4": "Random forest",
    "L5": "XGBoost",
}


def write_tables() -> None:
    log = "explain.sta303_v2:log"
    classes = "explain.sta303_v2:classes"
    flow = [
        ("Rows in the four Toronto Police files", f"{log}.source_rows"),
        (
            "Removed: occurrence outside 2014 to 2023, or invalid date",
            f"{log}.rows_outside_2014_2023_or_invalid_date",
        ),
        ("Rows in the unified table", f"{log}.ledger_final_rows"),
        ("Removed: no neighbourhood (NSA)", f"{log}.nsa_rows_dropped"),
        ("Rows used by the models", f"{log}.model_rows"),
    ]
    body = [f"{label} & {tex(fmt(ref))} \\\\" for label, ref in flow]
    cls = [
        f"{name} & {tex(fmt(f'{classes}.{name}'))} \\\\"
        for name in ("Robbery", "Auto Theft", "Break and Enter", "Theft Over")
    ]
    (GENERATED / "tab_flow.tex").write_text(
        HEADER
        + "\\begin{tabular}{@{}lr@{}}\n\\toprule\nStep & Rows \\\\\n\\midrule\n"
        + "\n".join(body)
        + "\n\\midrule\n\\multicolumn{2}{@{}l}{\\textit{Model rows by class}} \\\\\n"
        + "\n".join(cls)
        + "\n\\bottomrule\n\\end{tabular}\n"
    )

    def ci(base: str) -> str:
        return (
            f"{tex(fmt(f'{base}.estimate'))} [{tex(fmt(f'{base}.lo'))}, {tex(fmt(f'{base}.hi'))}]"
        )

    rows: list[str] = []
    for design, title in (
        (DESIGN_A, "Neighbourhood-grouped 5-fold cross-validation"),
        (DESIGN_B, "Temporal holdout (train to 2021, test 2022 to 2023)"),
    ):
        rows.append(f"\\multicolumn{{6}}{{@{{}}l}}{{\\textit{{{title}}}}} \\\\")
        names = ["L1", "L2", "L3", "L4", "L5", "L2-nopremises", "L5-nopremises"]
        for name in names:
            base = f"predict.ablation:designs.{design}.variants.{name}"
            rung, _, suffix = name.partition("-")
            label = f"{rung} {RUNG_LABEL[rung]}" + (", no premises" if suffix else "")
            cells = [
                ci(f"{base}.roc_auc"),
                ci(f"{base}.pr_auc"),
                ci(f"{base}.f1"),
                tex(fmt(f"{base}.precision.estimate")),
                tex(fmt(f"{base}.recall.estimate")),
            ]
            rows.append(f"{label} & " + " & ".join(cells) + " \\\\")
        if design == DESIGN_A:
            rows.append("\\midrule")
    (GENERATED / "tab_metrics.tex").write_text(
        HEADER
        + "\\begin{tabular}{@{}lccccc@{}}\n\\toprule\nModel & ROC-AUC & PR-AUC & F1 & Precision & Recall \\\\\n\\midrule\n"
        + "\n".join(rows)
        + "\n\\bottomrule\n\\end{tabular}\n"
    )
    print("tables: tab_flow.tex, tab_metrics.tex")


def write_figures() -> None:
    import vl_convert as vlc

    specs = BUILD / "specs"
    out = BUILD / "figures"
    out.mkdir(parents=True, exist_ok=True)
    subprocess.run(
        ["node", "scripts/export-paper-specs.mjs", str(specs)], cwd=ROOT / "web", check=True
    )
    vlc.register_font_directory(str(ROOT / ".cache" / "fonts" / "inter"))
    theme = json.loads((ROOT / "design" / "vega-theme.json").read_text())["light"]
    for path in sorted(specs.glob("fig*.vl.json")):
        spec = {
            "$schema": "https://vega.github.io/schema/vega-lite/v6.json",
            **json.loads(path.read_text()),
            "config": theme,
        }
        name = path.name.removesuffix(".vl.json")
        (out / f"{name}.pdf").write_bytes(vlc.vegalite_to_pdf(spec))
    print("figures:", ", ".join(sorted(p.name for p in out.glob("*.pdf"))))


if __name__ == "__main__":
    step = sys.argv[1] if len(sys.argv) > 1 else "all"
    GENERATED.mkdir(parents=True, exist_ok=True)
    if step in ("all", "tables"):
        write_tables()
    if step in ("all", "numbers"):
        write_numbers()
    if step in ("all", "figures"):
        write_figures()
