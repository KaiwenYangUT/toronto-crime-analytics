"""Generate every consumer of design/tokens.json (standard library plus the tca package).

    python tools/gen_tokens.py           # write the generated files
    python tools/gen_tokens.py --check   # fail if a generated file is out of date (CI drift check)

Outputs: web/src/styles/tokens.css, design/vega-theme.json, paper/generated/colors.tex.
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "pipeline" / "src"))
from tca.figures.theme import category_domain, load_tokens, vega_config

HEADER = "Generated by tools/gen_tokens.py from design/tokens.json. Do not edit by hand."


def css_vars(tokens: dict, mode: str, indent: str = "  ") -> str:
    c = tokens["color"][mode]
    lines = [
        f"{indent}--bg: {c['bg']};",
        f"{indent}--surface: {c['surface']};",
        f"{indent}--border: {c['border']};",
        f"{indent}--text: {c['text']};",
        f"{indent}--text-muted: {c['text-muted']};",
        f"{indent}--accent: {c['accent']};",
    ]
    for k, v in c["category"].items():
        lines.append(f"{indent}--cat-{k}: {v};")
    for i, v in enumerate(c["ordinal"], start=1):
        lines.append(f"{indent}--ordinal-{i}: {v};")
    for i, v in enumerate(c["density"], start=1):
        lines.append(f"{indent}--density-{i}: {v};")
    return "\n".join(lines)


def tokens_css(tokens: dict) -> str:
    t = tokens["type"]
    base = [
        f"  --font-ui: '{t['font_ui']}', system-ui, sans-serif;",
        f"  --font-serif: '{t['font_serif']}', Georgia, serif;",
        f"  --measure: {t['measure']};",
        f"  --radius: {tokens['radius']}px;",
        f"  --focus-ring: {tokens['focus_ring']}px;",
    ]
    for name, s in t["scale"].items():
        base.append(f"  --text-{name}: {s['size'] / 16:g}rem;")
        base.append(f"  --leading-{name}: {s['line']};")
    for i, v in enumerate(tokens["space"], start=1):
        base.append(f"  --space-{i}: {v}px;")
    for i, v in enumerate(tokens["breakpoints"], start=1):
        base.append(f"  --bp-{i}: {v}px;")
    return (
        f"/* {HEADER} */\n"
        ":root {\n"
        + "\n".join(base)
        + "\n"
        + css_vars(tokens, "light")
        + "\n  color-scheme: light dark;\n}\n\n"
        '@media (prefers-color-scheme: dark) {\n  :root:not([data-theme="light"]) {\n'
        + css_vars(tokens, "dark", "    ")
        + "\n  }\n}\n\n"
        ':root[data-theme="dark"] {\n' + css_vars(tokens, "dark") + "\n}\n"
    )


def vega_theme_json(tokens: dict) -> str:
    out = {
        "_generated": HEADER,
        "light": vega_config(tokens, "light"),
        "dark": vega_config(tokens, "dark"),
        "categories": category_domain(tokens),
    }
    return json.dumps(out, indent=2) + "\n"


def colors_tex(tokens: dict) -> str:
    """Light-mode colours for the paper (printed output is light)."""
    c = tokens["color"]["light"]
    lines = [f"% {HEADER}"]
    names = {
        "text": c["text"],
        "textmuted": c["text-muted"],
        "accent": c["accent"],
        "border": c["border"],
        "surface": c["surface"],
    }
    names.update({"cat" + k.replace("-", ""): v for k, v in c["category"].items()})
    for name, hexv in names.items():
        lines.append(f"\\definecolor{{tca{name}}}{{HTML}}{{{hexv.lstrip('#').upper()}}}")
    return "\n".join(lines) + "\n"


OUTPUTS = {
    ROOT / "web/src/styles/tokens.css": tokens_css,
    ROOT / "design/vega-theme.json": vega_theme_json,
    ROOT / "paper/generated/colors.tex": colors_tex,
}


def main(argv: list[str]) -> int:
    tokens = load_tokens()
    stale = []
    for path, build in OUTPUTS.items():
        text = build(tokens)
        if "--check" in argv:
            if not path.exists() or path.read_text() != text:
                stale.append(path.relative_to(ROOT))
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text)
            print("wrote", path.relative_to(ROOT))
    if stale:
        print("out of date:", *map(str, stale))
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
